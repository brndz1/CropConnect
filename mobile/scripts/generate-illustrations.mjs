// Turns the product illustrations of the visual system (assets/illustrations/*.svg) into src/components/illustrations.ts,
// which react-native-svg renders on every platform without a Metro SVG transformer. Run: npm run generate:illustrations
import { readdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const folder = resolve(here, "../assets/illustrations")
const target = resolve(here, "../src/components/illustrations.ts")

const files = (await readdir(folder)).filter((file) => file.endsWith(".svg")).sort()
const entries = []
for (const file of files) {
  const xml = (await readFile(resolve(folder, file), "utf8")).replace(/\s*\n\s*/g, " ").trim()
  const key = file.replace(/\.svg$/, "").replace(/_(\w)/g, (_, c) => c.toUpperCase())
  entries.push(`  ${key}: ${JSON.stringify(xml)},`)
}

await writeFile(
  target,
  `// Generated by scripts/generate-illustrations.mjs from assets/illustrations. Do not edit.\n\n` +
    `export const illustrations = {\n${entries.join("\n")}\n} as const\n\n` +
    `export type IllustrationName = keyof typeof illustrations\n`,
)
console.warn(`Wrote ${target}`)
