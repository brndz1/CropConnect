// Generates src/api/schema.d.ts from the gateway's OpenAPI document (docs/openapi.json), so every request and
// response the app uses is typed from the real contract. Run it after the API changes: npm run generate:api
//
// ASP.NET Core describes numbers as `["integer", "string"]` with a numeric pattern, because it would also accept
// them as strings. The gateway always sends JSON numbers, so the string alternative is dropped before generating.
import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(here, "../../docs/openapi.json")
const target = resolve(here, "../src/api/schema.d.ts")

function numbersOnly(node) {
  if (Array.isArray(node)) return node.map(numbersOnly)
  if (!node || typeof node !== "object") return node
  const copy = Object.fromEntries(Object.entries(node).map(([key, value]) => [key, numbersOnly(value)]))
  if (
    Array.isArray(copy.type) &&
    copy.type.includes("string") &&
    copy.type.some((t) => t === "integer" || t === "number")
  ) {
    copy.type = copy.type.filter((t) => t !== "string")
    if (copy.type.length === 1) copy.type = copy.type[0]
    delete copy.pattern
  }
  return copy
}

// Enums are also described as nullable (`enum: [..., null]`, and `oneOf: [null, enum]` on each property) because of
// how .NET maps them. The services never send a null enum in a response, so responses get the plain enum; request
// bodies keep the null where the API accepts it (e.g. a partial update).
function strictEnums(spec) {
  const schemas = spec.components.schemas
  const enumNames = new Set()
  for (const [name, schema] of Object.entries(schemas)) {
    if (Array.isArray(schema.enum)) {
      schema.enum = schema.enum.filter((value) => value !== null)
      enumNames.add(name)
    }
  }
  const isEnumRef = (node) => typeof node?.$ref === "string" && enumNames.has(node.$ref.split("/").pop())
  for (const [name, schema] of Object.entries(schemas)) {
    if (!name.endsWith("Response")) continue
    for (const [property, node] of Object.entries(schema.properties ?? {})) {
      const options = node.oneOf ?? node.anyOf
      if (Array.isArray(options) && options.some(isEnumRef) && options.some((option) => option.type === "null")) {
        schema.properties[property] = options.find(isEnumRef)
      }
    }
  }
  return spec
}

const spec = strictEnums(numbersOnly(JSON.parse(await readFile(source, "utf8"))))
const ast = await openapiTS(spec, { enumValues: false, defaultNonNullable: true })
const header =
  "// Generated by scripts/generate-api.mjs from docs/openapi.json. Do not edit: run `npm run generate:api`.\n\n"
await writeFile(target, header + astToString(ast))
console.warn(`Wrote ${target}`)
